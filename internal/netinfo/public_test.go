package netinfo

import "testing"

func TestIsPublic(t *testing.T) {
	public := []string{"1.1.1.1", "9.255.255.255", "11.0.0.1", "100.63.255.255", "100.128.0.1", "172.32.0.1", "198.17.255.255",
		"198.20.0.1", "223.255.255.255", "2606:4700::1111", "::ffff:1.1.1.1"}
	inner := []string{"10.1.2.3", "100.64.0.1", "100.127.255.255", "127.0.0.1", "169.254.1.1", "172.16.0.1", "172.31.255.255", "192.168.1.1",
		"192.0.2.10", "198.18.0.1", "198.19.255.255", "198.51.100.7", "203.0.113.7", "224.0.0.1", "255.255.255.255", "0.0.0.0",
		"::", "::1", "fc00::1", "fd12::1", "fe80::1", "fe80::1%en0", "2001:db8::1", "::ffff:10.0.0.1", "", "example.com"}
	for _, ip := range public {
		if !IsPublic(ip) {
			t.Errorf("%s: публичный, а признан внутренним", ip)
		}
	}
	for _, ip := range inner {
		if IsPublic(ip) {
			t.Errorf("%q: внутренний, а признан публичным", ip)
		}
	}
}
